package main

// The declarative shell.
//
// `files` can already hold a hand-written .zshrc, and for a config someone already
// owns that is the right answer. But nobody should have to paste the same six
// `eval "$(... init zsh)"` lines into every manifest to get a usable prompt, so
// [shell] generates them.
//
// Integrations are not a list the user maintains: spawn already knows every package
// in the env, so fzf, zoxide, direnv and starship are wired up when they are present
// and skipped when they are not. A manifest says what it wants, not how to wire it.

import (
	"fmt"
	"strings"
)

type shellConfig struct {
	Use     string            `toml:"use"`     // bash (default) or zsh
	Prompt  string            `toml:"prompt"`  // plain (default) or starship
	History *bool             `toml:"history"` // persist shell history; default true
	Aliases map[string]string `toml:"aliases"`
	Init    string            `toml:"init"` // extra lines, verbatim, last
}

// Where persisted history lives. It is a directory because persist entries are
// directories, and the shell is pointed at a file inside it.
const historyDir = "/root/.local/state"

func (s shellConfig) declared() bool {
	return s.Use != "" || s.Prompt != "" || s.History != nil || len(s.Aliases) > 0 || s.Init != ""
}

func (s shellConfig) use() string {
	if s.Use == "" {
		return "bash"
	}
	return s.Use
}

func (s shellConfig) persistHistory() bool {
	if !s.declared() {
		return false
	}
	// On by default: a shell that forgets everything the moment you leave is not the
	// "nice shell" anyone is asking for.
	return s.History == nil || *s.History
}

func (m *Manifest) validateShell() error {
	s := m.Shell
	if u := s.Use; u != "" && u != "bash" && u != "zsh" {
		return fmt.Errorf("shell.use %q is not bash or zsh", u)
	}
	if p := s.Prompt; p != "" && p != "plain" && p != "starship" {
		return fmt.Errorf("shell.prompt %q is not plain or starship", p)
	}
	for k := range s.Aliases {
		if strings.ContainsAny(k, " \t'\"=$`\\") || k == "" {
			return fmt.Errorf("shell alias %q is not a plain name", k)
		}
	}
	return nil
}

// shellPackages are the packages [shell] implies. Declaring shell.use = "zsh" and then
// having to remember to add zsh to tools would be a trap.
func (s shellConfig) packages() []string {
	if !s.declared() {
		return nil
	}
	var ps []string
	if s.use() == "zsh" {
		ps = append(ps, "zsh")
	}
	if s.Prompt == "starship" {
		ps = append(ps, "starship")
	}
	return ps
}

// rcPath is the file the chosen shell reads on an interactive start.
func (s shellConfig) rcPath() string {
	if s.use() == "zsh" {
		return "/root/.zshrc"
	}
	return "/root/.bashrc"
}

// shellBin is the interactive shell `spawn up` drops you into.
func (m *Manifest) shellBin(prof string) string {
	return prof + "/bin/" + m.Shell.use()
}

// has reports whether a package is in the env, so an integration is only wired up
// when the tool backing it actually exists.
func (m *Manifest) has(pkg string) bool {
	for _, p := range m.resolved {
		if p == pkg {
			return true
		}
	}
	return false
}

// rc renders the generated shell config. It is written before the manifest's own
// `files`, so declaring the rc path explicitly overrides all of this.
func (m *Manifest) rc(prof string) string {
	s := m.Shell
	sh := s.use()
	var b strings.Builder
	b.WriteString("# Generated by spawn from [shell] in the manifest.\n")
	b.WriteString("# Declare this file in [files] to replace it entirely.\n\n")

	// An rc file is read by non-interactive shells too in some cases; integrations
	// that touch the line editor must not run then.
	b.WriteString("case $- in *i*) ;; *) return ;; esac\n\n")

	if m.has("starship") && s.Prompt == "starship" {
		fmt.Fprintf(&b, "eval \"$(starship init %s)\"\n", sh)
	} else if sh == "bash" {
		// A prompt that shows the env name, because the whole point is knowing which
		// box you are in.
		fmt.Fprintf(&b, "PS1='%s> '\n", m.Name)
	} else {
		fmt.Fprintf(&b, "PROMPT='%s> '\n", m.Name)
	}

	if m.has("zoxide") {
		fmt.Fprintf(&b, "eval \"$(zoxide init %s)\"\n", sh)
	}
	if m.has("direnv") {
		fmt.Fprintf(&b, "eval \"$(direnv hook %s)\"\n", sh)
	}
	if m.has("atuin") {
		fmt.Fprintf(&b, "eval \"$(atuin init %s --disable-up-arrow)\"\n", sh)
	}
	if m.has("fzf") {
		// fzf-share is how nixpkgs exposes the shell integration files; guard it so
		// the rc still works if fzf is later removed from the manifest.
		fmt.Fprintf(&b, "if command -v fzf-share >/dev/null; then\n"+
			"  source \"$(fzf-share)/key-bindings.%s\"\n"+
			"  source \"$(fzf-share)/completion.%s\" 2>/dev/null\n"+
			"fi\n", sh, sh)
	}
	if sh == "zsh" {
		b.WriteString("autoload -Uz compinit && compinit -d /root/.cache/zcompdump\n")
		// These ship as plain .zsh files under the profile's share directory, so
		// source them by real path. ${ZSH_AUTOSUGGEST} is nothing anyone sets, so
		// guessing at a variable meant they silently never loaded.
		for _, p := range []struct{ pkg, file string }{
			{"zsh-autosuggestions", "zsh-autosuggestions/zsh-autosuggestions.zsh"},
			// Syntax highlighting must come last or it misses earlier widgets.
			{"zsh-syntax-highlighting", "zsh-syntax-highlighting/zsh-syntax-highlighting.zsh"},
		} {
			if m.has(p.pkg) {
				fmt.Fprintf(&b, "[ -r %s/share/%s ] && source %s/share/%s\n",
					prof, p.file, prof, p.file)
			}
		}
	}

	if s.persistHistory() {
		// Pointed at the persisted directory, so history outlives `spawn rm`.
		if sh == "zsh" {
			fmt.Fprintf(&b, "\nHISTFILE=%s/zsh_history\nHISTSIZE=50000\nSAVEHIST=50000\n"+
				"setopt INC_APPEND_HISTORY SHARE_HISTORY HIST_IGNORE_DUPS\n", historyDir)
		} else {
			fmt.Fprintf(&b, "\nHISTFILE=%s/bash_history\nHISTSIZE=50000\nHISTFILESIZE=50000\n"+
				"shopt -s histappend\n", historyDir)
		}
	}

	if len(s.Aliases) > 0 {
		b.WriteString("\n")
		for _, k := range sortedKeys(s.Aliases) {
			fmt.Fprintf(&b, "alias %s=%s\n", k, shellQuote(s.Aliases[k]))
		}
	}
	if s.Init != "" {
		b.WriteString("\n# shell.init\n")
		b.WriteString(strings.TrimRight(s.Init, "\n"))
		b.WriteString("\n")
	}
	return b.String()
}

// shellQuote wraps a value in single quotes for the generated rc file. An alias value
// is arbitrary shell, so the quoting has to be exact rather than approximate.
func shellQuote(v string) string {
	return "'" + strings.ReplaceAll(v, "'", `'\''`) + "'"
}

// seedShell writes the generated rc into the env, and reports the persist entry it
// needs so history survives.
func (m *Manifest) seedShell(prof string) error {
	if !m.Shell.declared() {
		return nil
	}
	root := envRootfsPath(m.Name, m.Shell.rcPath())
	if _, err := writeIfChanged(root, []byte(m.rc(prof)), 0o644); err != nil {
		return fmt.Errorf("seeding %s: %w", m.Shell.rcPath(), err)
	}
	return nil
}
