package main

// Bringing the tunnel up, in the one order that is actually safe.
//
//  1. install the default-drop ruleset, with a pinned hole for the endpoint
//  2. start the VPN client
//  3. wait for the tunnel interface
//
// Doing it the other way round leaks for the length of the handshake, and leaks again
// every time the tunnel drops. Because nftables matches the output interface by name,
// step 1 can reference tun0/wg0 before it exists, which is what makes this ordering
// possible rather than merely desirable.

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Where the generated network files live inside the env.
const (
	netDir      = "/etc/spawn"
	nftFile     = netDir + "/egress.nft"
	vpnConfFile = netDir + "/vpn.conf"
	netUpScript = netDir + "/netup.sh"
)

// vpnPackages are added to the env automatically. Declaring [vpn] and then having to
// remember openvpn, nftables and iproute2 by hand would be a trap, and forgetting
// nftables in particular would silently disable the kill switch.
func (m *Manifest) networkPackages() []string {
	var ps []string
	if m.effectiveEgress() != egressAllow {
		ps = append(ps, "nftables", "iproute2")
	}
	switch m.VPN.Kind {
	case "openvpn":
		ps = append(ps, "openvpn")
	case "wireguard":
		// wireguard-tools for wg/wg-quick, wireguard-go as the userspace fallback
		// when the kernel module is unavailable.
		ps = append(ps, "wireguard-tools", "wireguard-go")
	}
	return ps
}

// networkCaps are the privileges the policy and the tunnel need. Spawn adds them
// because it knows they are required, and `spawn check` prints the effective set so
// the privilege surface stays visible rather than hidden.
func (m *Manifest) networkCaps() (caps []string, devices []string) {
	if m.effectiveEgress() != egressAllow {
		caps = append(caps, "NET_ADMIN", "NET_RAW")
	}
	if m.VPN.declared() {
		caps = append(caps, "NET_ADMIN")
		devices = append(devices, "/dev/net/tun")
	}
	return caps, devices
}

// vpnConfigBody returns the VPN configuration text. A secret handle is read from the
// tmpfs stage, so the config never lands in the nix store or in spawn's state; a path
// is read from disk.
func (m *Manifest) vpnConfigBody(manifestDir string) ([]byte, error) {
	conf := m.VPN.Conf
	if strings.HasPrefix(conf, "secret:") {
		name := strings.TrimPrefix(conf, "secret:")
		stage, err := secretsStage(m.Name)
		if err != nil {
			return nil, err
		}
		b, err := os.ReadFile(filepath.Join(stage, name))
		if err != nil {
			return nil, fmt.Errorf("vpn.config secret %q is not staged: %w", name, err)
		}
		return b, nil
	}
	p, err := resolveHostPath(conf, manifestDir)
	if err != nil {
		return nil, err
	}
	return os.ReadFile(p)
}

// netupScript renders the in-env script that applies the policy and connects.
func (m *Manifest) netupScript(prof string) string {
	var b strings.Builder
	b.WriteString("#!/usr/bin/env bash\n")
	b.WriteString("# Generated by spawn. Applies the egress policy, then connects.\n")
	b.WriteString("set -u\n")
	fmt.Fprintf(&b, "export PATH=%s/bin:$PATH\n\n", prof)

	if m.effectiveEgress() != egressAllow {
		b.WriteString("# Policy first: nftables matches the output interface by name, so these\n")
		b.WriteString("# rules can name the tunnel before it exists. Nothing leaves until it does.\n")
		fmt.Fprintf(&b, "nft -f %s || { echo 'spawn: FAILED to apply the egress policy' >&2; exit 1; }\n\n", nftFile)
	}

	if !m.VPN.declared() {
		b.WriteString("exit 0\n")
		return b.String()
	}

	iface := m.VPN.tunnelIface()
	switch m.VPN.Kind {
	case "openvpn":
		fmt.Fprintf(&b, `# OpenVPN, backgrounded. --dev %s so the policy's interface name matches.
if pgrep -x openvpn >/dev/null; then echo "spawn: openvpn already running"; else
  openvpn --config %s --dev %s --daemon --log %s/openvpn.log \
    --script-security 1 || { echo 'spawn: openvpn failed to start' >&2; exit 1; }
fi
`, iface, vpnConfFile, iface, netDir)
	case "wireguard":
		fmt.Fprintf(&b, `# Prefer the kernel module; it autoloads on the netlink request even in a
# rootless userns. Fall back to the userspace implementation, which needs only
# /dev/net/tun and so works anywhere OpenVPN does.
if ! ip link show %s >/dev/null 2>&1; then
  if ! ip link add %s type wireguard 2>/dev/null; then
    echo "spawn: kernel wireguard unavailable, using wireguard-go"
    WG_QUICK_USERSPACE_IMPLEMENTATION=wireguard-go wireguard-go %s \
      || { echo 'spawn: wireguard-go failed' >&2; exit 1; }
  fi
fi
wg setconf %s <(grep -vE '^\s*(Address|DNS|MTU|Table|PreUp|PostUp|PreDown|PostDown)\s*=' %s) \
  || { echo 'spawn: wg setconf failed' >&2; exit 1; }
# Addresses and routes come from the config's Address lines, which wg itself ignores.
while read -r addr; do ip addr replace "$addr" dev %s; done < <(
  grep -E '^\s*Address\s*=' %s | sed 's/.*=//' | tr ',' '\n' | tr -d ' ')
ip link set %s up
ip route replace default dev %s 2>/dev/null || true
`, iface, iface, iface, iface, vpnConfFile, iface, vpnConfFile, iface, iface)
	}

	fmt.Fprintf(&b, `
# Wait for the tunnel, but never longer than this: a hung connect must not look
# like a working one.
up=0
for i in $(seq 1 100); do
  if ip link show %s >/dev/null 2>&1 && ip -br addr show %s | grep -q 'UP\|UNKNOWN'; then
    up=1; break
  fi
  sleep 0.1
done
if [ "$up" != 1 ]; then
  echo "spawn: %s did not come up within 10s; the kill switch is still in force" >&2
  exit 1
fi
`, iface, iface, iface)

	if m.VPN.routeAll() {
		fmt.Fprintf(&b, `
# Send everything through the tunnel. The kill switch only stops traffic leaving by
# another route; without this the env would simply have no egress at all unless the
# server pushed a default route itself.
ip route replace default dev %s 2>/dev/null || echo "spawn: could not route the default via %s" >&2
`, iface, iface)
	}
	fmt.Fprintf(&b, "\necho \"spawn: %s is up\"\nexit 0\n", iface)
	return b.String()
}

// seedNetwork writes the policy, the VPN config and the connect script into the env.
func (m *Manifest) seedNetwork(prof, manifestDir string) error {
	if m.effectiveEgress() == egressAllow && !m.VPN.declared() {
		return nil
	}
	dir := envRootfsPath(m.Name, netDir)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}

	var eps []endpoint
	if m.VPN.declared() {
		body, err := m.vpnConfigBody(manifestDir)
		if err != nil {
			return err
		}
		eps, err = parseEndpoints(m.VPN.Kind, string(body), nil)
		if err != nil {
			return err
		}
		// A VPN config carries keys, so it is never world-readable.
		if _, err := writeIfChanged(envRootfsPath(m.Name, vpnConfFile), body, 0o600); err != nil {
			return err
		}
		if len(m.VPN.DNS) > 0 {
			// With vpn-only egress the host resolver is unreachable by design, so
			// the env needs a resolver that lives inside the tunnel.
			var rc strings.Builder
			rc.WriteString("# Generated by spawn from vpn.dns\n")
			for _, d := range m.VPN.DNS {
				fmt.Fprintf(&rc, "nameserver %s\n", d)
			}
			if _, err := writeIfChanged(envRootfsPath(m.Name, "/etc/resolv.conf"), []byte(rc.String()), 0o644); err != nil {
				return err
			}
		}
	}

	if rs := m.nftRuleset(eps); rs != "" {
		if _, err := writeIfChanged(envRootfsPath(m.Name, nftFile), []byte(rs), 0o600); err != nil {
			return err
		}
	}
	if _, err := writeIfChanged(envRootfsPath(m.Name, netUpScript), []byte(m.netupScript(prof)), 0o700); err != nil {
		return err
	}
	return nil
}

// bringUpNetwork runs the connect script inside the env.
func (m *Manifest) bringUpNetwork(prof string) error {
	if m.effectiveEgress() == egressAllow && !m.VPN.declared() {
		return nil
	}
	out, err := podmanOut("exec", "-e", "PATH="+prof+"/bin", cname(m.Name),
		prof+"/bin/bash", netUpScript)
	if out != "" {
		fmt.Fprintln(os.Stderr, indentLines(out))
	}
	if err != nil {
		return fmt.Errorf("network setup failed: %w", err)
	}
	return nil
}

func indentLines(s string) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	for i, l := range lines {
		lines[i] = "  " + l
	}
	return strings.Join(lines, "\n")
}
